const express = require("express");

const router = express.Router();

const {
    handleStripeWebhook
} = require("../controllers/stripeWebhookController");

/**
 * @swagger
 * /api/webhooks/stripe:
 *   post:
 *     summary: Receive Stripe webhook events
 *     description: |
 *       Receives Stripe events and verifies the Stripe-Signature
 *       header using the configured webhook secret.
 *       This endpoint is intended for Stripe, not ordinary users.
 *     tags: [Webhooks]
 *     parameters:
 *       - in: header
 *         name: Stripe-Signature
 *         required: true
 *         schema:
 *           type: string
 *         description: Signature generated by Stripe
 *     requestBody:
 *       required: true
 *       content:
 *         application/json:
 *           schema:
 *             type: object
 *             description: Raw Stripe event payload
 *     responses:
 *       200:
 *         description: Webhook event processed
 *       400:
 *         description: Invalid webhook signature or payload
 */

router.post("/", handleStripeWebhook);

module.exports = router;